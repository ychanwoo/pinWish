import assert from 'node:assert/strict'
import { expect } from '@playwright/test'

// Called only with freshly created validation accounts by validate-web-live.mjs.
export async function validateReleaseBrowser({ page, browser, origin, user, request, checks, shareTokens }) {
  const record = check => { checks.push(check); console.log('Passed:', check) }
  const button = name => page.getByRole('button', { name, exact: true }).filter({ visible: true }).first()
  const closeDetail = async () => {
    const close = button('Close place details')
    if (await close.count()) await close.click()
  }
  const options = async name => button('Options for ' + name).click()
  const ok = async (path, method = 'GET', body) => {
    const result = await request(user.token, path, method, body)
    assert.ok(result.status >= 200 && result.status < 300, `${path}: ${result.status}`)
    return result.body
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await button('Edit personal note').click()
  await page.getByRole('textbox', { name: 'Personal note', exact: true }).fill('PRIVATE RELEASE CHECK')
  await button('Save note').click()
  await expect(page.locator('.personal-note')).toContainText('PRIVATE RELEASE CHECK')
  await button('Unvisited').click()
  await expect(button('Visited')).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await page.locator('.place-card-title').filter({ hasText: 'Griffith Observatory' }).click()
  await expect(button('Visited')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.personal-note')).toContainText('PRIVATE RELEASE CHECK')
  record('Deployed note and visit edits persist after reload')
  await closeDetail()
  const collection = (await ok('/collections')).items[0]
  await button('Map colors').click()
  const pine = button('Pine for ' + collection.name)
  await pine.click()
  await expect(pine).toHaveAttribute('aria-pressed','true')
  await button('Close map colors').click()
  await page.reload()
  await button('Map colors').click()
  await expect(pine).toHaveAttribute('aria-pressed','true')
  await button('Close map colors').click()
  record('Deployed collection color persists and map renders')

  await options(collection.name)
  await page.getByRole('menuitem',{name:'Plan a trip',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Plan a trip',exact:true})).toBeVisible()
  await button('Review hours & time').click()
  await expect(page.getByRole('heading',{name:'Review hours & visit times',exact:true})).toBeVisible({timeout:60000})
  const date = new Date(Date.now()+7*86400000).toISOString().slice(0,10)
  await page.getByLabel('Start date',{exact:true}).fill(date)
  await button('Create journey').click()
  await expect(page.getByRole('heading',{name:'Day by day',exact:true})).toBeVisible({timeout:60000})
  await page.getByLabel('Journey name',{exact:true}).fill('Release validation journey')
  await expect(button('Save journey')).toBeEnabled()
  await button('Save journey').click()
  await expect(page.getByRole('heading',{name:'Your saved trip',exact:true})).toBeVisible()
  const trips=(await ok('/itineraries?collectionId='+collection.id)).items
  const trip=trips.find(t=>t.name==='Release validation journey')
  assert.ok(trip)
  const saved=(await ok('/itineraries/'+trip.id)).item
  const stops=saved.plan.days.flatMap(d=>d.stops)
  assert.equal(new Set(stops.map(s=>s.id)).size,stops.length)
  assert.equal(stops.length,9) // The visited observatory is deliberately excluded by default.
  const unknown=stops.filter(s=>s.hoursSource==='unknown').length, suggested=stops.filter(s=>s.hoursSource==='suggested').length
  await expect(page.getByText('Hours unverified · check before visiting',{exact:true})).toHaveCount(unknown)
  await expect(page.getByText('Suggested time · confirm opening hours',{exact:true})).toHaveCount(suggested)
  await expect(page.getByText('Route unavailable · arrange transport separately', {exact:true})).toHaveCount(stops.filter(s=>s.travel===null).length)
  record(`Journey uncertainty labels match saved results: ${unknown} unknown-hours visits, ${suggested} suggested visits`)
  await page.screenshot({path:'/tmp/pinwish-release-journey.png',fullPage:true})
  await button('Create sharing link').click()
  const tripLink=await page.getByLabel('Sharing link',{exact:true}).inputValue()
  shareTokens.push({type:'trip',token:new URL(tripLink).hash.slice(6)})
  const guest=await browser.newContext(), guestPage=await guest.newPage()
  try {
    await guestPage.goto(tripLink)
    await expect(guestPage.getByRole('heading',{name:'Release validation journey',exact:true})).toBeVisible()
    await expect(guestPage.getByText('PRIVATE RELEASE CHECK')).toHaveCount(0)
    await guestPage.setViewportSize({width:390,height:844})
    assert.ok(await guestPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await guestPage.screenshot({path:'/tmp/pinwish-release-shared-journey-mobile.png',fullPage:true})
    await ok('/itineraries/'+trip.id+'/sharing','DELETE')
    await guestPage.reload()
    await expect(guestPage.getByRole('heading',{name:'Journey unavailable',exact:true})).toBeVisible()
  } finally { await guest.close() }
  await button('Close trip planner').click()
  await page.reload()
  await options(collection.name)
  await page.getByRole('menuitem',{name:'Plan a trip',exact:true}).click()
  await page.getByRole('button',{name:/Release validation journey/}).click()
  await button('Edit journey').click()
  await button('Review hours & time').click()
  await expect(page.getByLabel('Start date',{exact:true})).toHaveValue(date)
  await button('Create journey').click()
  await expect(button('Save journey')).toBeEnabled({timeout:60000})
  await page.getByLabel('Journey name',{exact:true}).fill('Updated release journey')
  await button('Save journey').click()
  await expect(page.getByRole('heading',{name:'Your saved trip',exact:true})).toBeVisible()
  await button('Close trip planner').click()
  const updated=(await ok('/itineraries/'+trip.id)).item
  assert.equal(updated.name,'Updated release journey')
  await ok('/itineraries/'+trip.id,'DELETE',{version:updated.version})
  assert.equal((await request(user.token,'/itineraries/'+trip.id)).status,404)
  record('All nine unvisited selections scheduled; journey saved, reopened, edited, shared, revoked and deleted against real AWS')

  await options(collection.name)
  await page.getByRole('menuitem',{name:'Share collection',exact:true}).click()
  await button('Create sharing link').click()
  const link=await page.getByLabel('Read-only link',{exact:true}).inputValue()
  shareTokens.push({type:'collection',token:new URL(link).hash.slice(7)})
  const publicContext=await browser.newContext(), publicPage=await publicContext.newPage()
  try {
    await publicPage.goto(link)
    await expect(publicPage.getByRole('heading',{name:collection.name,exact:true})).toBeVisible()
    await expect(publicPage.getByText('PRIVATE RELEASE CHECK')).toHaveCount(0)
    await publicPage.setViewportSize({width:390,height:844})
    assert.ok(await publicPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    await ok('/collections/'+collection.id+'/sharing','DELETE')
    await publicPage.reload()
    await expect(publicPage.getByRole('heading',{name:'This link is unavailable',exact:true})).toBeVisible()
  } finally { await publicContext.close() }
  await page.goto(origin)
  record('Anonymous collection sharing excludes private notes and revocation removes access')

  await button('Save a place').click()
  await button('Place search').click()
  await page.getByLabel('Place name or address',{exact:true}).fill('California State University San Marcos')
  await page.getByLabel('City or region',{exact:false}).fill('San Marcos, California')
  await button('Search').click()
  await expect(page.locator('.direct-result').first()).toBeVisible({timeout:60000})
  await page.locator('.direct-result').filter({hasText:'California State University San Marcos'}).first().click()
  await expect(page.getByRole('region',{name:'Selected place'})).toBeVisible({timeout:60000})
  await button('Add to map').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('#place-heading')).toContainText('California State University')
  const direct=(await ok('/places')).items.find(p=>p.searchOrigin)
  assert.ok(direct)
  // Photo completion increments the place version; reopen the persisted record
  // before editing, as the conflict guidance requests.
  await page.reload()
  await page.locator('.place-card-title').filter({hasText:'California State University San Marcos'}).click()
  await button('Unvisited').click()
  await expect(button('Visited')).toHaveAttribute('aria-pressed','true')
  await closeDetail()
  await button('Create collection').click()
  await page.getByLabel('Collection name',{exact:true}).fill('Release collection')
  await page.getByRole('dialog').getByRole('button',{name:'Create collection',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await options('Release collection')
  await page.getByRole('menuitem',{name:'Edit name',exact:true}).click()
  await page.getByLabel('Collection name',{exact:true}).fill('Renamed release collection')
  await button('Save name').click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(button('Options for Renamed release collection')).toBeVisible()
  const destination=(await ok('/collections')).items.find(c=>c.name==='Renamed release collection')
  await page.locator('.collection-link').filter({hasText:collection.name}).first().click()
  await page.locator('.place-card-title').filter({hasText:'California State University San Marcos'}).click()
  await page.getByLabel('Collection',{exact:true}).selectOption(destination.name)
  await button('Move').click()
  await expect(page.getByLabel('Collection',{exact:true})).toHaveValue(destination.name)
  await expect(button('Move')).toBeDisabled()
  await expect.poll(async () => (await ok('/places/'+direct.id)).item.collectionId).toBe(destination.id)
  await closeDetail()
  await page.reload()
  await options('Renamed release collection')
  await page.getByRole('menuitem',{name:'Delete',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Yes',exact:true}).click()
  await expect(button('Options for Renamed release collection')).toHaveCount(0)
  const preserved=(await ok('/places/'+direct.id)).item
  assert.equal(preserved.visited,true)
  assert.notEqual(preserved.collectionId,destination.id)
  record('Real direct search/save and visited state; collection create/rename/move/delete preserves the saved place')
  const privateContext=await browser.newContext(), privatePage=await privateContext.newPage()
  try {
    await privatePage.goto(origin+'/?view=detail&place='+direct.id)
    await privatePage.getByRole('button',{name:'Sign in',exact:true}).first().click()
    await expect(privatePage.getByRole('heading',{name:'Welcome back'})).toBeVisible()
    await expect(privatePage.locator('#place-heading')).toHaveCount(0)
  } finally {await privateContext.close()}
  record('Private saved-place links require authentication and do not expose details anonymously')
  await button('Sign out').click()
  await expect(button('Sign in')).toBeVisible()
  await button('Save a place').click()
  await page.getByLabel('Instagram post link',{exact:true}).fill('https://www.instagram.com/p/DfFCMjzk02S/')
  await button('Find place').click()
  await expect(page.getByRole('dialog').getByRole('heading',{name:'Welcome back'})).toBeVisible()
  record('Real sign-out clears session and signed-out saving prompts sign-in')
}
